const ink: Record<string, string> = {
  '1': '#fff3db',
  '2': '#ee6260',
  '3': '#ffc96c',
  '4': '#58ab82',
  '5': '#28745f',
  '6': '#9d3443',
}
export function paintIcon(el: HTMLElement, name: string) {
  const rows = art[name]
  if (!rows) return
  const canvas = document.createElement('canvas')
  canvas.width = Math.max(...rows.map((row) => row.length))
  canvas.height = rows.length
  canvas.setAttribute('aria-hidden', 'true')
  const c = canvas.getContext('2d')!
  rows.forEach((row, y) =>
    Array.from(row).forEach((pixel, x) => {
      if (ink[pixel]) {
        c.fillStyle = ink[pixel]
        c.fillRect(x, y, 1, 1)
      }
    }),
  )
  el.replaceChildren(canvas)
}
